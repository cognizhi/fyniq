-- Invoices (PRD-001 FR-AR-03, FM-1, FM-2, FM-3, SOD-3; p1-sales tasks 1.1 to 1.3).
--
-- A customer's invoice is a document of its own: versioned like a bill, posted (issued) by the rule invoice@1 through
-- the posting service, numbered from its own sequence (FR-ORG-04, INV- by default, gap-free: numbered when it is
-- issued). Its entry holds no new kind of line. Invoices join the approval engine as bills did (000077): a request to
-- issue one above the self-approval threshold, or, in Founder mode, to void or edit one (FM-1); and an organisation's
-- policy for them. The checks are widened NOT VALID and validated by 000110 (squawk: constraint-missing-not-valid).

