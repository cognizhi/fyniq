// ------------------------------------------------------------- quotes and invoices sent by email (FR-AR-06; p1-sales task 5.2)
//
// A sent quote or order, or an issued invoice, goes to the customer's billing email (or one given for the send) from the
// organisation's invoices sender, with the subject and body of the email template that applies to the customer and
// the PDF of its current version attached, rendered with the document template that applies to it. The PDF is kept as
// the document's evidence (generated by Fyniq), and the send records the version, the message, the file and the
// template version, so what the customer received can be shown and proved. A draft is never sent; sending again sends
// the same version again. Delivery follows the message's outcome and the provider's events.

// DocumentSendOut is a quote or invoice sent by email.
type DocumentSendOut struct {
	ID              string    `json:"id" format:"uuid" doc:"The send's ID." example:"01928f6e-7a3b-7c41-9d2e-5f8a1b3c4e70"`
	Version         int       `json:"version" doc:"The document's version that was sent." example:"1"`
	To              string    `json:"to" doc:"Whom it was sent to." example:"accounts@acme.example"`
	SentAt          time.Time `json:"sent_at" doc:"When it was sent." example:"2026-10-24T09:30:00Z"`
	SentBy          *Person   `json:"sent_by,omitempty" doc:"Who sent it."`
	Delivery        string    `json:"delivery" enum:"sent,delivered,viewed,bounced" doc:"sent until the provider says more; delivered; viewed, once the customer opened the link it carried; or bounced, when the provider refused or returned it." example:"sent"`
	Status          string    `json:"message_status" enum:"queued,accepted,failed,unknown" doc:"The email message's own outcome, as the delivery log shows it." example:"accepted"`
	EvidenceID      string    `json:"evidence_id" format:"uuid" doc:"The PDF that was sent, kept in the document's evidence." example:"01928f6e-7a3b-7c41-9d2e-5f8a1b3c4e80"`
	PDFSHA256       string    `json:"pdf_sha256" doc:"The PDF's SHA-256, in hex." example:"a18760db1dd480808a9d4b2fd9b460608c4312c8998317e5ef444d83c0061bda"`
	TemplateSource  string    `json:"template_source" enum:"contact,default,platform" doc:"The document template that rendered it: the customer's, the organisation's default, or the Classic starter." example:"platform"`
	TemplateVersion int       `json:"template_version" doc:"That template's published version; 0 for the starter." example:"0"`
}

// EmailDocument says where a quote or invoice is emailed.
type EmailDocument struct {
	To string `json:"to,omitempty" maxLength:"254" doc:"The address to send it to; left out, the customer's billing email." example:"accounts@acme.example"`
}

// emailDocumentInput is what emailing a document reads from its request, whichever document it is.
type emailDocumentInput struct {
	IdempotencyKey, IfMatch, Prefer string
	Body                            *EmailDocument
}

type emailInvoiceInput struct {
	InvoicePath
	KeyHeader
	IfMatchHeader
	PreferHeader
	Body *EmailDocument `required:"false"`
}

type emailQuoteInput struct {
	QuotePath
	KeyHeader
	IfMatchHeader
	PreferHeader
	Body *EmailDocument `required:"false"`
}

// sendsOut are a document's sends; viewed says which messages' links were opened.
func sendsOut(sends []storage.DocumentSend, viewed map[uuid.UUID]bool) []DocumentSendOut {
	out := []DocumentSendOut{}
	for i := range sends {
		s := sends[i]
		out = append(out, DocumentSendOut{ID: s.ID.String(), Version: s.DocumentVersion, To: s.Recipient, SentAt: s.SentAt.UTC(), SentBy: personOf(s.SentBy),
			Delivery: salesdoc.Delivery(&s, viewed[s.MessageID]), Status: s.MessageStatus, EvidenceID: s.EvidenceID.String(), PDFSHA256: s.PDFSHA256,
			TemplateSource: s.TemplateSource, TemplateVersion: s.TemplateVersion})
	}
	return out
}

// sentBy are the senders of sends, for naming.
func sentBy(sends []DocumentSendOut) []*Person {
	out := make([]*Person, 0, len(sends))
	for _, s := range sends {
		out = append(out, s.SentBy)
	}
	return out
}

// sender is the API's sender of quotes and invoices (package salesmail), rendering through the render service.
func (a *API) sender() salesmail.Sender {
	out := salesmail.Sender{Store: a.deps.Store, Staging: a.deps.Staging, Origin: a.deps.Origin, Clock: a.deps.Clock}
	if a.deps.Outbox != nil {
		out.Outbox = *a.deps.Outbox
	}
	if a.deps.Renderer != nil {
		out.Render = a.renderDocumentAt
	}
	return out
}

// sendProblem words salesmail's refusals for the API.
func sendProblem(kind string, err error) error {
	var missing *salesmail.MissingParticulars
	switch {
	case errors.Is(err, salesmail.ErrNoRenderer):
		return problem(doctemplate.CodeRenderer, "No render service is configured, so the document cannot be sent.", "Ask the operator to configure the render service")
	case errors.Is(err, salesmail.ErrChanged):
		return problem(CodeStale, fmt.Sprintf("The %s changed while it was being sent.", kind), "Read it again and send it again")
	case errors.As(err, &missing):
		return problem(salesdoc.CodeParticulars, fmt.Sprintf("The tax invoice lacks %s, which IRAS requires, so it is not sent.", strings.Join(missing.Missing, ", ")),
			"Add the missing details in Settings › Organisation or on the customer, then send it again")
	}
	return err
}

// emailDocument runs a send end to end: read and render, stage the PDF, and record the send with run's view of the
// document after it, under the request's Idempotency-Key and If-Match.
func emailDocument[B any](ctx context.Context, a *API, id uuid.UUID, invoiceSend bool, in emailDocumentInput, request any,
	etagOf func(ctx context.Context, u storage.UnitOfWork, doc storage.Document) (string, error),
	view func(ctx context.Context, u storage.UnitOfWork) (B, error)) (written[B], error) {
	if strings.TrimSpace(in.IfMatch) == "" {
		return written[B]{}, checkIfMatch(in.IfMatch, "")
	}
	if a.deps.Outbox == nil || a.deps.Staging == nil {
		return written[B]{}, problem(CodeUnavailable, "Email cannot be sent from this deployment.", "Ask the operator to configure the outbox and the file store")
	}
	preview := wantsPreview(in.Prefer)
	to := ""
	if in.Body != nil {
		to = strings.TrimSpace(in.Body.To)
	}
	if to != "" {
		addr, err := netmail.ParseAddress(to)
		if err != nil || addr.Name != "" || addr.Address != to || strings.ContainsAny(to, "\r\n") {
			return written[B]{}, invalid([]FieldProblem{{Code: CodeInvalid, Field: "body.to", Message: "is not an email address",
				Fix: "Send one address, such as accounts@acme.example"}})
		}
	}
	p, _ := authn.From(ctx)
	sender := a.sender()
	var tag string
	s, err := sender.Prepare(ctx, p.Organisation, id, invoiceSend, to, !preview, func(ctx context.Context, u storage.UnitOfWork, doc storage.Document) (err error) {
		tag, err = etagOf(ctx, u, doc)
		return err
	})
	if err != nil {
		return written[B]{}, sendProblem(s.Kind, err)
	}
	if err := checkIfMatch(in.IfMatch, tag); err != nil {
		return written[B]{}, err
	}
	key := ""
	if !preview {
		if key, err = sender.Stage(ctx, p.Organisation, s); err != nil {
			logFailure(ctx, err)
			return written[B]{}, problem(CodeUnavailable, "The PDF could not be stored.", "Try again in a few minutes.")
		}
	}
	w, err := write(ctx, a, in.IdempotencyKey, in.Prefer, request, http.StatusOK, func(ctx context.Context, u storage.UnitOfWork) (B, error) {
		var zero B
		if preview {
			doc, err := u.Documents().Lock(ctx, id)
			if err != nil {
				return zero, err
			}
			if doc.Status != storage.DocumentPosted || doc.Version != s.Version {
				return zero, sendProblem(s.Kind, salesmail.ErrChanged)
			}
		} else if err := sender.Record(ctx, u, p.Organisation, id, s, key); err != nil {
			return zero, sendProblem(s.Kind, err)
		}
		return view(ctx, u)
	})
	if (err != nil || w.Replayed) && key != "" {
		_ = a.deps.Staging.Delete(context.WithoutCancel(ctx), key) // no row uses it; the sweeper would delete it a day later
	}
	return w, err
}

func registerDocumentSends(a *API) {
	codes := []string{CodeNotFound, CodeStale, CodeIfMatchRequired, CodeInvalid, CodeIdempotencyReused, CodeIdempotencyBusy, CodeIdempotencyOld,
		CodeUnavailable, salesdoc.CodeNotSent, salesdoc.CodeNoRecipient, salesdoc.CodeUnready, salesdoc.CodeParticulars, doctemplate.CodeRenderer,
		storage.CodeRetry, storage.CodeLockTimeout}
	register(a, authz.EmailInvoice, huma.Operation{
		OperationID: "emailInvoice", Method: http.MethodPost, Path: "/v1/invoices/{invoice_id}/email", Tags: []string{"Sales"},
		Summary: "Email an invoice to the customer",
		Description: "Emails an issued invoice (FR-AR-06) to the customer's billing email, or the address given, from the organisation's " +
			"invoices sender, with the subject and body of the email template that applies to the customer and the PDF of its current " +
			"version attached, rendered with the document template that applies (FR-TPL-05). A tax invoice that lacks a particular IRAS " +
			"requires, such as the customer's address, is not sent (SALESDOC-05); a draft or voided one never is (SALESDOC-03). Sending " +
			"again sends the same version again. Side effects: the PDF in the invoice's evidence (source generated), the email message " +
			"in the delivery log, the send, and their audit events; its delivery state follows the provider's events. Needs If-Match with " +
			"the invoice's ETag. Idempotent with Idempotency-Key; Prefer: return=preview checks it and sends nothing.",
	}, append([]string{invoice.CodeNotInvoice, invoice.CodeBadDraft, salesdoc.CodeNotInvoice}, codes...),
		func(ctx context.Context, in *emailInvoiceInput) (*invoiceOutput, error) {
			id, err := parseID("invoice_id", in.InvoiceID)
			if err != nil {
				return nil, err
			}
			view := func(ctx context.Context, u storage.UnitOfWork, doc storage.Document) (Invoice, error) {
				v, err := a.invoiceView(ctx, u)
				if err != nil {
					return Invoice{}, err
				}
				return a.invoiceOf(ctx, u, v, doc, true)
			}
			w, err := emailDocument(ctx, a, id, true, emailDocumentInput{in.IdempotencyKey, in.IfMatch, in.Prefer, in.Body}, in,
				func(ctx context.Context, u storage.UnitOfWork, doc storage.Document) (string, error) {
					i, err := view(ctx, u, doc)
					return invoiceETag(i), err
				},
				func(ctx context.Context, u storage.UnitOfWork) (Invoice, error) {
					doc, err := u.Documents().Get(ctx, id)
					if err != nil {
						return Invoice{}, err
					}
					return view(ctx, u, doc)
				})
			if err != nil {
				return nil, err
			}
			if w.Previewed {
				return &invoiceOutput{Status: w.Status, Applied: applied(w), Body: w.Body}, nil
			}
			return &invoiceOutput{Status: w.Status, ETag: invoiceETag(w.Body), Replayed: replayedHeader(w.Replayed), Body: w.Body}, nil
		})

	register(a, authz.EmailQuote, huma.Operation{
		OperationID: "emailQuote", Method: http.MethodPost, Path: "/v1/quotes/{quote_id}/email", Tags: []string{"Sales"},
		Summary: "Email a quote or sales order to the customer",
		Description: "Emails a sent quote or order (FR-AR-06, FR-AR-16) to the customer's billing email, or the address given, from the " +
			"organisation's invoices sender, with the subject and body of the email template that applies to the customer and the PDF " +
			"of its current version attached, rendered with the quote template that applies (FR-TPL-05). A draft or cancelled one is " +
			"never sent (SALESDOC-03); sendQuote sends a draft first. Side effects: the PDF in the quote's evidence (source generated), " +
			"the email message in the delivery log, the send, and their audit events. Needs If-Match with the quote's ETag. Idempotent " +
			"with Idempotency-Key; Prefer: return=preview checks it and sends nothing.",
	}, append([]string{quote.CodeNotQuote, quote.CodeBadDraft, invoice.CodeBadDraft}, codes...),
		func(ctx context.Context, in *emailQuoteInput) (*quoteOutput, error) {
			id, err := parseID("quote_id", in.QuoteID)
			if err != nil {
				return nil, err
			}
			view := func(ctx context.Context, u storage.UnitOfWork, doc storage.Document) (Quote, error) {
				base, err := baseOf(ctx, u)
				if err != nil {
					return Quote{}, err
				}
				return a.quoteOf(ctx, u, base, doc, false)
			}
			w, err := emailDocument(ctx, a, id, false, emailDocumentInput{in.IdempotencyKey, in.IfMatch, in.Prefer, in.Body}, in,
				func(ctx context.Context, u storage.UnitOfWork, doc storage.Document) (string, error) {
					q, err := view(ctx, u, doc)
					return quoteETag(q), err
				},
				func(ctx context.Context, u storage.UnitOfWork) (Quote, error) {
					doc, err := u.Documents().Get(ctx, id)
					if err != nil {
						return Quote{}, err
					}
					return view(ctx, u, doc)
				})
			if err != nil {
				return nil, err
			}
			if w.Previewed {
				return &quoteOutput{Status: w.Status, Applied: applied(w), Body: w.Body}, nil
			}
			return &quoteOutput{Status: w.Status, ETag: quoteETag(w.Body), Replayed: replayedHeader(w.Replayed), Body: w.Body}, nil
		})
}
