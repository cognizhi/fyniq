-- engine now covers the object bank_rule with the operation bank_rule.auto_apply, which a person holding A on "Bank
-- transactions, categorise" approves after seeing the rule's back-test, and no one who asked for it (FM-1). The widened
-- checks are added NOT VALID and validated by 000150 (squawk: constraint-missing-not-valid).

