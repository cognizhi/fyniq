var update = flag.Bool("update", false, "rewrite the replay golden files in testdata/replay/")

type replayCase struct {
	name string
	j    Journal
	s    Settings
}

// replayCases are the fixed documents each rule version replays (QA-ENG-06). A new rule version gets cases of its own
// and a golden file; an old version's file never changes.
func replayCases(t *testing.T) map[string][]replayCase {
	retained := Account{ID: uuid.MustParse("0192f1a0-0000-7000-8000-000000003100"), Code: "3100", Active: true}
	opening := withShareCapital()
	opening.Accounts[retained.ID] = retained
	fx := sale(t, "1200.00")
	fx.Version, fx.Memo = 3, "Retainer, part in US dollars"
	fx.Lines = append(fx.Lines,
		JournalLine{AccountID: usdBank.ID, Amount: amt(t, "100.00", usd), Rate: usdRate(t, "1.3472"), Description: "Wise USD"},
		JournalLine{AccountID: sales.ID, Amount: amt(t, "-134.72", sgd)})
	odd := sale(t, "0.01")
	odd.Memo = ""
	odd.Lines = append(odd.Lines,
		JournalLine{AccountID: usdBank.ID, Amount: amt(t, "0.01", usd), Rate: usdRate(t, "1.3549"), Description: "rounds to a cent"},
		JournalLine{AccountID: sales.ID, Amount: amt(t, "-0.01", sgd)})
	return map[string][]replayCase{
		RuleManualJournal: {
			{"a base-currency journal", sale(t, "1200.00"), settings},
			{"a foreign-currency line at its rate", fx, settings},
			{"a cent of US dollars under RND-FX", odd, settings},
		},
		RuleOpeningBalance: {
			{"the bank against share capital", Journal{ID: docID, Version: 1, Date: day, Memo: "Opening balances", Lines: []JournalLine{
				{AccountID: bank.ID, Amount: amt(t, "10000.00", sgd), Description: "DBS"},
				{AccountID: shareCapital.ID, Amount: amt(t, "-10000.00", sgd)},
			}}, opening},
			{"with retained earnings, as changed", Journal{ID: docID, Version: 2, Date: day, Lines: []JournalLine{
				{AccountID: bank.ID, Amount: amt(t, "12480.00", sgd)},
				{AccountID: shareCapital.ID, Amount: amt(t, "-10000.00", sgd)},
				{AccountID: retained.ID, Amount: amt(t, "-2480.00", sgd), Description: "Profit to 30 September"},
			}}, opening},
		},
	}
}

// render is an entry as the golden files keep it: every stored field, one line each.
func render(name string, e Entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "== %s\nposting_date %s\nsource %s %s v%d\nrule_version %s\nposting_identity %s\nmemo %q\n", name,
		e.PostingDate.Format("2006-01-02"), e.Source.Type, e.Source.ID, e.Source.Version, e.RuleVersion, e.PostingIdentity, e.Memo)
	for i, l := range e.Lines {
		fmt.Fprintf(&b, "line %d %s %s %s × %s = %s %s %q\n", i+1, l.AccountID, l.Amount, l.Amount.Currency().Code, rateText(l.Rate),
			l.Base, l.Base.Currency().Code, l.Description)
	}
	return b.String()
}

// Each rule version reproduces exactly what it produced over the same documents (ENG-06): a change to a version's
// output fails here, and reviewing the golden file's diff is the only way past it, so a changed rule becomes a new
// version instead. Every version the engine has has cases, and an unknown version is refused.
// req: ENG-06
// req: QA-ENG-06
func TestEveryRuleVersionReplaysItsGoldenEntries(t *testing.T) {
	cases := replayCases(t)
	for rule := range Rules {
		if len(cases[rule]) == 0 {
			t.Errorf("rule version %s has no replay cases: add them, and its golden file", rule)
		}
	}
	for rule, cs := range cases {
		if Rules[rule] == nil {
			t.Errorf("replay cases for %s, which is not a rule version", rule)
			continue
		}
		var b strings.Builder
		fmt.Fprintf(&b, "# What %s posts for each replay case. Generated by TestEveryRuleVersionReplaysItsGoldenEntries;\n"+
			"# a rule version's output never changes (ENG-06): a different output is a new rule version.\n", rule)
		for _, c := range cs {
			e, err := Replay(rule, c.j, c.s)
			if err != nil {
				t.Fatalf("%s, %s: %v", rule, c.name, err)
			}
			again, err := Replay(rule, c.j, c.s)
			if err != nil || len(Differences(e, again)) > 0 {
				t.Fatalf("%s, %s: a second run differs: %v %v", rule, c.name, err, Differences(e, again))
			}
			b.WriteString(render(c.name, e))
		}
		path := filepath.Join("testdata", "replay", rule+".golden")
		if *update {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("%v (run `go test ./internal/domain/ledger -run %s -update` for a new rule version, and review it)", err, t.Name())
		}
		if string(want) != b.String() {
			t.Errorf("%s no longer reproduces its entries (ENG-06): make the change a new rule version.\n--- want\n%s\n--- got\n%s", rule, want, b.String())
		}
	}
	if _, err := Replay("manual_journal@0", sale(t, "1.00"), settings); !slices.Contains(codes(err), CodeUnknownRule) {
		t.Errorf("an unknown rule version: %v", err)
	}
}

// Differences names every stored field that differs, and compares rates by value.
// req: ENG-06
func TestDifferencesNameEveryStoredField(t *testing.T) {
	j := sale(t, "1200.00")
	j.Lines = append(j.Lines, JournalLine{AccountID: usdBank.ID, Amount: amt(t, "100.00", usd), Rate: usdRate(t, "1.3472")},
		JournalLine{AccountID: sales.ID, Amount: amt(t, "-134.72", sgd)})
	want, err := PostJournal(j, settings)
	if err != nil {
		t.Fatal(err)
	}
	same := want
	same.Lines = slices.Clone(want.Lines)
	padded, err := money.ParseRate("1.3472000000", usd, sgd, "document")
	if err != nil {
		t.Fatal(err)
	}
	same.Lines[2].Rate = padded
	if d := Differences(want, same); len(d) != 0 {
		t.Errorf("the same entry, its rate padded as stored: %v", d)
	}
	got := same
	got.Lines = slices.Clone(same.Lines)
	got.Memo, got.PostingIdentity, got.RuleVersion = "Changed", "x", "manual_journal@2"
	got.PostingDate = got.PostingDate.AddDate(0, 0, 1)
	got.Source.Version = 9
	got.Lines[0].Description = "other"
	got.Lines[1].AccountID = bank.ID
	got.Lines[2].Base = amt(t, "134.73", sgd)
	got.Lines[2].Amount = amt(t, "100.01", usd)
	other, err := money.ParseRate("1.3473", usd, sgd, "document")
	if err != nil {
		t.Fatal(err)
	}
	got.Lines[2].Rate = other
	d := strings.Join(Differences(want, got), "\n")
	for _, field := range []string{"posting_date", "source", "rule_version", "posting_identity", "memo", "line 1 description", "line 2 account",
		"line 3 amount", "line 3 rate", "line 3 base"} {
		if !strings.Contains(d, field+":") {
			t.Errorf("no difference in %s: %s", field, d)
		}
	}
	if d := Differences(want, Entry{}); !slices.Contains(d, "lines: 0, not 4") {
		t.Errorf("a missing line: %v", d)
	}
}
