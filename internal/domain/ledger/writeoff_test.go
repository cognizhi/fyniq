var writeOffID = uuid.MustParse("0192f1a0-0000-7000-8000-0000000a0ff0")

func writeOff(t testing.TB, amount string, cur money.Currency, stored *money.Rate, clears string, account Account) WriteOff {
	r := money.Identity(sgd)
	if stored != nil {
		r = *stored
	}
	w := WriteOff{ID: writeOffID, Version: 1, Date: day, Memo: "INV-0140 Acme Analytics: bad debt", InvoiceID: invoiceID, Amount: amt(t, amount, cur),
		StoredRate: r, Account: account.ID}
	if clears != "" {
		c := amt(t, clears, sgd)
		w.Clears = &c
	}
	return w
}

// FR-AR-17 and the posting rule "Bad-debt write-off", worked by hand: a write-off credits 1100 with the amount at the
// invoice's stored rate and debits the reason's account, in SGD, with the carrying amount it clears; nothing came in, so
// there is no realised FX.
//   - All of an SGD invoice of 1,000.00: Cr 1100 1,000.00, Dr the account 1,000.00.
//   - USD 40.00 of an invoice at 1.34: Cr 1100 USD 40.00 = S$53.60, Dr the account S$53.60.
//   - The last US cent of an invoice at 1.5, which carries S$0.01: Cr 1100 USD 0.01 = S$0.02, a base-only S$0.01 back on
//     1100 (the residual), and Dr the account S$0.01.
//
// req: FR-AR-17
// req: ledger/posting-rules Bad-debt write-off
func TestPostWriteOff(t *testing.T) {
	s := selling()
	for _, c := range []struct {
		name         string
		w            WriteOff
		want, settle string
	}{
		{"all of an SGD invoice", writeOff(t, "1000.00", sgd, nil, "1000.00", software),
			"1100 -1000.00 SGD = -1000.00; 6120 1000.00 SGD = 1000.00", "a1110 1000.00 = 1000.00 fx 0.00 tol 0.00"},
		{"part of a USD invoice", writeOff(t, "40.00", usd, usdRate(t, "1.34"), "", software),
			"1100 -40.00 USD = -53.60; 6120 53.60 SGD = 53.60", "a1110 40.00 = 53.60 fx 0.00 tol 0.00"},
		{"the last cent", writeOff(t, "0.01", usd, usdRate(t, "1.5"), "0.01", software),
			"1100 -0.01 USD = -0.02; 1100 0.00 USD = 0.01; 6120 0.01 SGD = 0.01", "a1110 0.01 = 0.01 fx 0.00 tol 0.00"},
	} {
		e, x, err := PostWriteOff(c.w, s)
		if err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		if got := legs(s, e); got != c.want {
			t.Errorf("%s:\n got %s\nwant %s", c.name, got, c.want)
		}
		if got := tolerances([]Settlement{x}); got != c.settle {
			t.Errorf("%s: settled %s, want %s", c.name, got, c.settle)
		}
		if e.RuleVersion != RuleWriteOff || e.Source != (Source{SourceWriteOff, writeOffID.String(), 1}) || e.PostingIdentity != WriteOffIdentity(writeOffID, 1, RuleWriteOff) {
			t.Errorf("%s: the entry's identity: %+v", c.name, e)
		}
	}
}

// What the write-off rule refuses comes back together (ENG-22): no date, an amount that is not positive, an account the
// rule posts to by itself, a group heading, and a residual larger than a cent's worth.
// req: FR-AR-17
// req: QA-RPT-02
func TestTheWriteOffRuleRefusesWhatCannotPost(t *testing.T) {
	s := selling()
	w := writeOff(t, "0.00", sgd, nil, "", receivables)
	w.Date = time.Time{}
	if _, _, err := PostWriteOff(w, s); !slices.Equal(codes(err), []string{CodeNoDate, CodeRuleAccount, CodePaymentAmount}) {
		t.Errorf("every refusal: %v", err)
	}
	if _, _, err := PostWriteOff(writeOff(t, "10.00", sgd, nil, "", group), s); !slices.Equal(codes(err), []string{CodeGroupAccount}) {
		t.Errorf("a group heading: %v", err)
	}
	if _, _, err := PostWriteOff(writeOff(t, "10.00", sgd, nil, "12.00", software), s); !slices.Equal(codes(err), []string{CodePaymentAmount}) ||
		!strings.Contains(err.Error(), "Write off what is open of the invoice") {
		t.Errorf("more than a cent left: %v", err)
	}
	noAR := selling()
	delete(noAR.Accounts, receivables.ID)
	if _, _, err := PostWriteOff(writeOff(t, "10.00", sgd, nil, "", software), noAR); !slices.Equal(codes(err), []string{CodeSystemRole}) {
		t.Errorf("no accounts receivable: %v", err)
	}
}

// Each write-off rule version reproduces exactly what it produced over the same write-offs (ENG-06).
// req: ENG-06
// req: QA-ENG-06
func TestEveryWriteOffRuleVersionReplaysItsGoldenEntries(t *testing.T) {
	cases := map[string][]struct {
		name string
		w    WriteOff
	}{
		RuleWriteOff: {
			{"all of an SGD invoice", writeOff(t, "1000.00", sgd, nil, "1000.00", software)},
			{"part of a USD invoice", writeOff(t, "40.00", usd, usdRate(t, "1.34"), "", software)},
			{"the last cent, with its residual", writeOff(t, "0.01", usd, usdRate(t, "1.5"), "0.01", software)},
		},
	}
	for rule := range WriteOffRules {
		if len(cases[rule]) == 0 {
			t.Errorf("rule version %s has no replay cases: add them, and its golden file", rule)
		}
	}
	for rule, cs := range cases {
		var b strings.Builder
		fmt.Fprintf(&b, "# What %s posts for each replay case. Generated by TestEveryWriteOffRuleVersionReplaysItsGoldenEntries;\n"+
			"# a rule version's output never changes (ENG-06): a different output is a new rule version.\n", rule)
		for _, c := range cs {
			e, x, err := ReplayWriteOff(rule, c.w, selling())
			if err != nil {
				t.Fatalf("%s, %s: %v", rule, c.name, err)
			}
			b.WriteString(render(c.name, e))
			fmt.Fprintf(&b, "settles %s %s %s = %s %s\n", x.DocumentID, x.Amount, x.Amount.Currency().Code, x.Base, x.Base.Currency().Code)
		}
		path := filepath.Join("testdata", "replay", rule+".golden")
		if *update {
			if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("%v (run `go test ./internal/domain/ledger -run %s -update` for a new rule version, and review it)", err, t.Name())
		}
		if string(want) != b.String() {
			t.Errorf("%s no longer reproduces its entries (ENG-06): make the change a new rule version.\n--- want\n%s\n--- got\n%s", rule, want, b.String())
		}
	}
	if _, _, err := ReplayWriteOff("write_off@0", WriteOff{}, selling()); !slices.Contains(codes(err), CodeUnknownRule) {
		t.Errorf("an unknown rule version: %v", err)
	}
}
